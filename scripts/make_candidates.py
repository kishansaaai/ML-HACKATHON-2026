"""Build candidate+feature tables and per-point reference labels for all development trips.

Outputs (git-ignored, regenerated by this script):
  data_cache/candidates/<part>/<trip>.parquet   one row per (obs_idx, arc_id): features + label
  data_cache/obs/<part>/<trip>.parquet          one row per GPS point: ref_arc (-1 undefined), ref_dist_m
  results/label_stats.csv                        label-alignment quality per trip
Only `train` and `student_test` are processed; evaluator data is never touched.
"""
from __future__ import annotations

import argparse
import time

import numpy as np
import pandas as pd
from joblib import Parallel, delayed

from pathsnap.candidates import CandidateConfig, build_candidates
from pathsnap.geo import TripGraph
from pathsnap.io import load_trip
from pathsnap.labels import derive_point_labels
from pathsnap.paths import CACHE_DIR, RESULTS_DIR, list_trips, trip_dir


def process(part: str, tid: str, cfg: CandidateConfig):
    t0 = time.time()
    trip = load_trip(trip_dir(part, tid), with_labels=True)
    graph = TripGraph(trip)
    ref, dist, stats = derive_point_labels(trip, graph, return_stats=True)
    cand = build_candidates(trip, graph, cfg)
    # label attaches AFTER features are built; features never see it
    cand["label"] = (cand["arc_id"].to_numpy() == ref[cand["obs_idx"].to_numpy()]).astype("int8")
    obs = pd.DataFrame({"trip_id": tid, "obs_idx": np.arange(trip.n_obs, dtype="int32"),
                        "ref_arc": ref.astype("int64"), "ref_dist_m": dist.astype("float32"),
                        "lon": trip.lon, "lat": trip.lat, "t": trip.t})
    for sub, df in (("candidates", cand), ("obs", obs)):
        d = CACHE_DIR / sub / part
        d.mkdir(parents=True, exist_ok=True)
        df.to_parquet(d / f"{tid}.parquet", index=False)
    has_ref = ref >= 0
    pos_obs = cand.loc[cand["label"] == 1, "obs_idx"].nunique()
    row = dict(part=part, trip_id=tid, n_cand_rows=len(cand), cand_per_obs=len(cand) / trip.n_obs,
               miss_rate=float(1 - pos_obs / max(has_ref.sum(), 1)), seconds=time.time() - t0, **stats.__dict__)
    return row


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--parts", nargs="+", default=["train", "student_test"])
    ap.add_argument("--limit", type=int, default=None, help="only the first N trips per part (debug)")
    ap.add_argument("--jobs", type=int, default=4)
    args = ap.parse_args()
    cfg = CandidateConfig.load()
    print("candidate config:", cfg)
    jobs = [(p, t) for p in args.parts for t in list_trips(p)[: args.limit]]
    rows = Parallel(n_jobs=args.jobs, verbose=5)(delayed(process)(p, t, cfg) for p, t in jobs)
    df = pd.DataFrame(rows)
    RESULTS_DIR.mkdir(exist_ok=True)
    df.to_csv(RESULTS_DIR / "label_stats.csv", index=False)
    print(df.groupby("part")[["n_cand_rows", "cand_per_obs", "miss_rate", "frac_labelled", "frac_ambiguous", "seconds"]].describe().T.to_string())


if __name__ == "__main__":
    main()

